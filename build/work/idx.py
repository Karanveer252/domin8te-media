def main():
    global PFX
    s = io.open(CSS, encoding='utf-8').read()
    for marker in (HEAD, '\n/* ============================================================\n   THE WORK MARK:',
                   '\n/* ============================================================\n   THE WORK INDEX:'):
        if marker in s:
            s = s[:s.index(marker)]
    out = [s.rstrip('\n'), HEAD, BASE_CSS] + [MOTION_CSS[i] for i in IDS]
    for i in IDS:
        out.append('html[data-v="editorial"][data-workidx="%s"] .wmk--%s{display:block}' % (i, i))
    io.open(CSS, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('v-editorial.css rewritten,', len('\n'.join(out)), 'chars')

    t = io.open(TPL, encoding='utf-8').read()
    svgs = []
    for i in IDS:
        PFX = i.capitalize()
        svgs.append('      <svg class="wmk wmk--%s" viewBox="0 0 %s %s" aria-hidden="true" focusable="false" '
                    'preserveAspectRatio="xMaxYMax meet">%s</svg>' % (i, f(W), f(H), BUILD[i]()))
    block = OPEN + '\n' + '\n'.join(svgs) + '\n' + CLOSE
    if OPEN not in t or CLOSE not in t:
        raise SystemExit('no WORKIDX region in the template')
    t = t[:t.index(OPEN)] + block + t[t.index(CLOSE) + len(CLOSE):]
    t = re.sub(r'data-workidx="[a-z]+"', 'data-workidx="%s"' % IDS[0], t)
    io.open(TPL, 'w', encoding='utf-8', newline='\n').write(t)
    print('template region rewritten,', len(block), 'chars for', len(IDS), 'motions; default', IDS[0])


if __name__ == '__main__':
    main()
