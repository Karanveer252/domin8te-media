OPEN = '      <!-- WORKIDX:START generated by work/idx.py, do not hand edit -->'
CLOSE = '      <!-- WORKIDX:END -->'

# Karan chose drop on 2026-09-18 and it shipped. The other four are in git history
# and in this file's docstring; add them back to IDS to compare again.
IDS = ['drop']
W, H = 520.0, 200.0
BASE = H * 0.80
CX = W * 0.70
W2, H2 = 62.0, 34.0
STEP = 26.0
CREAM = '#F2EDE3'
SPECTRUM = ['#E5322B', '#F2912F', '#F3CB3C', '#5CB246', '#0FA3C2', '#2E5FA8', '#7A3E97', '#D51C73']

PFX = ''


def gid():
    return 'wmk%sG' % PFX


def fid():
    return 'wmk%sF' % PFX


def f(v):
    return ('%.1f' % v).rstrip('0').rstrip('.')


def lingrad(name, x1, y1, x2, y2):
    st = ''.join('<stop offset="%d%%" stop-color="%s"/>'
                 % (round(i * 100 / (len(SPECTRUM) - 1)), c) for i, c in enumerate(SPECTRUM))
    return ('<linearGradient id="%s" gradientUnits="userSpaceOnUse" x1="%s" y1="%s" x2="%s" y2="%s">%s</linearGradient>'
            % (name, f(x1), f(y1), f(x2), f(y2), st))


def blur(name, amount, pad=80):
    return ('<filter id="%s" x="-%d%%" y="-%d%%" width="%d%%" height="%d%%">'
            '<feGaussianBlur stdDeviation="%s"/></filter>'
            % (name, pad, pad, 100 + pad * 2, 100 + pad * 2, f(amount)))


def defs(amount=11):
    return '<defs>' + lingrad(gid(), CX - W2, 0, CX + W2, 0) + blur(fid(), amount) + '</defs>'


def chev(cy):
    return 'M %s %s L %s %s L %s %s' % (f(CX - W2), f(cy - H2), f(CX), f(cy), f(CX + W2), f(cy - H2))


def lead(op='.25'):
    return ('<path d="M %s %s L %s %s" stroke="%s" stroke-opacity="%s" stroke-width="1.2"/>'
            % (f(0), f(BASE), f(CX - W2 - 30), f(BASE), CREAM, op))


SLOTS = [BASE - 32, BASE - 32 + STEP, BASE - 32 + STEP * 2]


def arrow(cy, cls='', op=None, extra=''):
    """one chevron, drawn with its glow: the shape Karan approved"""
    c = (' class="%s"' % cls) if cls else ''
    o = (' opacity="%s"' % op) if op is not None else ''
    return ('<g%s%s%s>'
            '<path d="%s" fill="none" stroke="url(#%s)" stroke-width="11" opacity=".32" '
            'stroke-linecap="round" stroke-linejoin="round" filter="url(#%s)"/>'
            '<path d="%s" fill="none" stroke="url(#%s)" stroke-width="3.4" '
            'stroke-linecap="round" stroke-linejoin="round"/>'
            '</g>' % (c, o, extra, chev(cy), gid(), fid(), chev(cy), gid()))


def ghost(cy):
    """the empty slot a moving arrow leaves behind, barely there"""
    return ('<path d="%s" fill="none" stroke="%s" stroke-opacity=".08" stroke-width="3.4" '
            'stroke-linecap="round" stroke-linejoin="round"/>' % (chev(cy), CREAM))


# ------------------------------------------------------------------- 1 drop
def svg_drop():
    """Karan's: the arrow falls slot to slot, each one left empty behind it"""
    ghosts = ''.join(ghost(y) for y in SLOTS)
    # the three that stand at rest, and one faller that travels between them
    rest = (arrow(SLOTS[0], 'wmk__d1') + arrow(SLOTS[1], 'wmk__d2') + arrow(SLOTS[2], 'wmk__d3'))
    faller = arrow(SLOTS[0], 'wmk__dfall', extra=' style="--step:%spx"' % f(STEP))
    return defs() + lead() + ghosts + rest + faller


# ------------------------------------------------------------------- 2 fall
def svg_fall():
    """endless rain through the three slots"""
    ghosts = ''.join(ghost(y) for y in SLOTS)
    drops = ''.join(arrow(SLOTS[0], 'wmk__f%d' % i, extra=' style="--step:%spx"' % f(STEP * 2))
                    for i in range(3))
    return defs() + lead() + ghosts + drops


# --------------------------------------------------------------- 3 collapse
def svg_collapse():
    """all three shift down together, the top slot opens"""
    ghosts = ''.join(ghost(y) for y in SLOTS)
    body = ''.join(arrow(SLOTS[i], 'wmk__c%d' % i, extra=' style="--step:%spx"' % f(STEP))
                   for i in range(3))
    return defs() + lead() + ghosts + body


# ------------------------------------------------------------------ 4 build
def svg_build():
    """arrows arrive from above and stack up, bottom first"""
    ghosts = ''.join(ghost(y) for y in SLOTS)
    body = ''.join(arrow(SLOTS[i], 'wmk__b%d' % i, extra=' style="--step:%spx"' % f(STEP * 2.2))
                   for i in range(3))
    return defs() + lead() + ghosts + body


# ---------------------------------------------------------------- 5 shuffle
def svg_shuffle():
    """a rotation: the lowest leaves, returns at the top, the others step down"""
    ghosts = ''.join(ghost(y) for y in SLOTS)
    body = ''.join(arrow(SLOTS[i], 'wmk__h%d' % i, extra=' style="--step:%spx"' % f(STEP))
                   for i in range(3))
    return defs() + lead() + ghosts + body


BUILD = {'drop': svg_drop, 'fall': svg_fall, 'collapse': svg_collapse,
         'build': svg_build, 'shuffle': svg_shuffle}

