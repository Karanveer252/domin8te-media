"""The work header's right column, which went empty when Karan removed the
paragraph beside the heading (2026-09-18).

Seventh round, and the brief is now precise. Karan described the motion he
wants: the arrow drops from the first slot to the second and the first slot is
left empty; it drops again to the third and the second is left empty; then they
all fill back in and it loops. That is `drop` below, built exactly so.

The four beside it are companions for that idea, all of them about arrows
*moving between slots* rather than a light passing over fixed ones:

  drop      Karan's: one arrow falls slot to slot, leaving each one empty
            behind it, then the stack fills again
  fall      endless rain: arrows keep falling through the three slots, the
            stack never empty and never still
  collapse  all three shift down together, the top slot opens, the lowest
            leaves the frame, then the stack snaps back
  build     the reverse: arrows arrive from above and stack up, bottom first,
            until all three stand, then it starts over
  shuffle   a rotation: the lowest arrow leaves and returns at the top while
            the others step down

The drawing is unchanged: the chevron Karan approved, three slots, sitting on
the heading's last baseline. Only what the arrows do is different.

Every one has a defined still state under prefers-reduced-motion.
All five are decorative: aria-hidden, no focus, no text.
Ids are namespaced per treatment (PFX); duplicates make the carets invisible.

  python C:\\Work\\domin8te-build\\work\\idx.py
"""
