def splice(text, open_m, close_m, block, where):
    if open_m in text and close_m in text:
        return text[:text.index(open_m)] + block + text[text.index(close_m) + len(close_m):]
    raise SystemExit('no CHARGE region in ' + where)


def main():
    # the template's drawings
    t = io.open(TPL, encoding='utf-8').read()
    block = T_OPEN + '\n' + '\n'.join(BUILD[i]() for i in IDS) + '\n' + T_CLOSE
    t = splice(t, T_OPEN, T_CLOSE, block, 'the template')
    if 'data-charge="' in t:
        t = re.sub(r'data-charge="[a-z]+"', 'data-charge="' + IDS[0] + '"', t)
    else:
        t = t.replace(' data-feel="', ' data-charge="' + IDS[0] + '" data-feel="', 1)
    io.open(TPL, 'w', encoding='utf-8', newline='\n').write(t)
    print('template region rewritten,', len(block), 'chars for', len(IDS), 'drawings; default', IDS[0])

    # the stylesheet's region, made at the end of the file the first time
    s = io.open(CSS, encoding='utf-8').read()
    shows = '\n'.join('html[data-charge="' + i + '"] .chg--' + i + '{display:block}' for i in IDS)
    css = C_OPEN + BASE_CSS + ''.join(ONE_CSS[i] for i in IDS) + shows + '\n' + C_CLOSE
    if C_OPEN in s and C_CLOSE in s:
        s = splice(s, C_OPEN, C_CLOSE, css, 'site.css')
    else:
        s = s.rstrip('\n') + '\n\n' + css + '\n'
    io.open(CSS, 'w', encoding='utf-8', newline='\n').write(s)
    print('site.css region rewritten,', len(css), 'chars')


if __name__ == '__main__':
    main()
