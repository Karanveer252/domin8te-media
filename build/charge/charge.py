def stops(pairs):
    return ''.join('<stop offset="' + o + '" stop-color="' + c + '"/>' for o, c in pairs)


def trail_grad(gid):
    """light that fades away below whatever has been let fly"""
    return ('<linearGradient id="' + gid + '" x1="0" y1="0" x2="0" y2="1">'
            '<stop offset="0" stop-color="#FFF1DC" stop-opacity=".95"/>'
            '<stop offset=".35" stop-color="#FF8A3D" stop-opacity=".6"/>'
            '<stop offset="1" stop-color="#FF5B1F" stop-opacity="0"/></linearGradient>')


def svg(name, viewbox, body):
    return ('      <svg class="chg chg--' + name + '" viewBox="' + viewbox + '" aria-hidden="true" focusable="false">'
            + body + '</svg>')


